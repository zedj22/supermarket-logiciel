  /// Localized label for a backend unit-type enum value (piece / kg / gram /
  /// liter / milliliter / meter / pack) or for a historical selling-unit name
  /// captured at checkout (`Box`, `Boîte`, `CARTON`, …).
  ///
  /// Match order: exact → case/diacritic-insensitive → raw code. The folded
  /// step is what lets a sale made with a unit named `Box` render as `Box` /
  /// `Boîte` / `علبة` in en / fr / ar (all three dictionaries carry the
  /// `box` and `boite` spellings for exactly this).
  static String unitLabel(String? code, String locale) {
    if (code == null || code.isEmpty) return '';
    final map = translations[locale];
    if (map == null) return code;
    final exact = map[code];
    if (exact != null) return exact;
    return map[_foldUnitCode(code)] ?? code;
  }

  /// Lower-cases [code] and drops Latin diacritics so `Boîte` → `boite`.
  static String _foldUnitCode(String code) {
    final lower = code.toLowerCase();
    final buffer = StringBuffer();
    for (final unit in lower.runes) {
      buffer.writeCharCode(_diacriticFold[unit] ?? unit);
    }
    return buffer.toString();
  }


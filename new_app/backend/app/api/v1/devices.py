@router.get(
    "",
    response_model=DeviceListResponse,
    summary="List registered devices",
    tags=["devices"],
)
def list_devices(
    _user: User = Depends(require_permission(PermissionScope.DEVICE_MANAGE)),
    service: DeviceService = Depends(_service),
) -> DeviceListResponse:
    devices, total = service.list_devices()
    return DeviceListResponse(
        items=[_to_response(d) for d in devices],
        total=total,
    )


@router.get(
    CODE_PATH,
    response_model=PairingCodeResponse,
    summary="Generate the current 6-digit pairing code",
    tags=["devices"],
)
def get_pairing_code(
    http_request: Request,
    _user: User = Depends(require_permission(PermissionScope.DEVICE_MANAGE)),
    service: DeviceService = Depends(_service),
) -> PairingCodeResponse:
    """Rotate the code on every call.

    Returned to a human only; never audited, never logged (§18).
    """
    code, generated_at, expires_at = service.rotate_pairing_code()
    remaining = max(0, int((expires_at - generated_at).total_seconds()))
    return PairingCodeResponse(
        code=code,
        generated_at=generated_at,
        expires_at=expires_at,
        expires_in_seconds=remaining,
        server_id=get_server_id(),
        http_port=settings.PORT,
    )


@router.post(
    "/{device_id}/approve",
    response_model=DeviceResponse,
    summary="Approve a pending device",
    tags=["devices"],
)
def approve_device(
    device_id: str,
    http_request: Request,
    user: User = Depends(require_permission(PermissionScope.DEVICE_MANAGE)),
    service: DeviceService = Depends(_service),
) -> DeviceResponse:
    device = _require_row(service, device_id)
    service.approve(device.id, user.id, actor_ip=_ip(http_request))
    refreshed = service.get_by_device_id(device_id)
    return _to_response(refreshed or device)


@router.post(
    "/{device_id}/deny",
    response_model=DeviceResponse,
    summary="Deny a pending pairing request",
    tags=["devices"],
)
def deny_device(
    device_id: str,
    http_request: Request,
    body: DeviceReasonRequest | None = None,
    user: User = Depends(require_permission(PermissionScope.DEVICE_MANAGE)),
    service: DeviceService = Depends(_service),
) -> DeviceResponse:
    device = _require_row(service, device_id)
    reason = body.reason if body is not None else None
    service.deny(device.id, user.id, reason, actor_ip=_ip(http_request))
    refreshed = service.get_by_device_id(device_id)
    return _to_response(refreshed or device)


@router.post(
    "/{device_id}/revoke",
    response_model=DeviceResponse,
    summary="Revoke an approved device",
    tags=["devices"],
)
def revoke_device(
    device_id: str,
    http_request: Request,
    body: DeviceReasonRequest | None = None,
    user: User = Depends(require_permission(PermissionScope.DEVICE_MANAGE)),
    service: DeviceService = Depends(_service),
) -> DeviceResponse:
    device = _require_row(service, device_id)
    reason = body.reason if body is not None else None
    service.revoke(device.id, user.id, reason, actor_ip=_ip(http_request))
    refreshed = service.get_by_device_id(device_id)
    return _to_response(refreshed or device)


def _require_row(service: DeviceService, device_id: str) -> Device:
    device = service.get_by_device_id(device_id)
    if device is None:
        raise NotFoundError(
            message="Device not found", details={"device_id": device_id}
        )
    return device

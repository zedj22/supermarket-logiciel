"""Devices API (Phase 16).

Unauthenticated handshake (allowlisted by the device guard, rate limited):
    POST   /api/v1/devices/pair                  — present the 6-digit code;
                                                   201 {pairing_id, status}
                                                   and no token, ever
    GET    /api/v1/devices/pairings/{pairing_id} — poll until approved
                                                   (returns the one-time
                                                   device token exactly once)

Authenticated, ``device_manage`` (owner Q2 — admin only):
    GET    /api/v1/devices
    GET    /api/v1/devices/pairing-code           — rotate / read the code
    POST   /api/v1/devices/{device_id}/approve
    POST   /api/v1/devices/{device_id}/deny
    POST   /api/v1/devices/{device_id}/revoke

``device_id`` in the path is the immutable machine identity (``pos-…``),
never the display name and never an IP address.
"""

from __future__ import annotations

import uuid

from fastapi import APIRouter, Depends, Request
from sqlalchemy.orm import Session

from app.api.dependencies import require_permission
from app.core.config import settings
from app.core.exceptions import NotFoundError
from app.core.server_identity import get_server_id
from app.db.session import get_db
from app.models.device import Device
from app.models.enums import PermissionScope
from app.models.user import User
from app.schemas.device import (
    DeviceListResponse,
    DevicePairingStatusResponse,
    DevicePairRequest,
    DevicePairResponse,
    DeviceReasonRequest,
    DeviceResponse,
    PairingCodeResponse,
)
from app.services.devices import (
    DeviceService,
    PairingRateLimitedError,
    pair_limiter_global,
    pair_limiter_ip,
)

router = APIRouter()

PAIR_PATH = "/pair"
POLL_PATH = "/pairings/{pairing_id}"
CODE_PATH = "/pairing-code"


def _service(db: Session = Depends(get_db)) -> DeviceService:
    return DeviceService(db)


def _ip(request: Request) -> str | None:
    return request.client.host if request.client else None


def _to_response(device: Device) -> DeviceResponse:
    approver = device.approver
    return DeviceResponse(
        id=device.id,
        device_id=device.device_id,
        display_name=device.display_name,
        status=device.status,
        client_version=device.client_version,
        approved_at=device.approved_at,
        approved_by=device.approved_by,
        approved_by_name=approver.full_name if approver is not None else None,
        rejected_at=device.rejected_at,
        revoked_at=device.revoked_at,
        last_seen_at=device.last_seen_at,
        last_ip=device.last_ip,
        requested_ip=device.requested_ip,
        created_at=device.created_at,
    )



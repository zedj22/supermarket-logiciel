@router.post(
    PAIR_PATH,
    response_model=DevicePairResponse,
    status_code=201,
    summary="Request pairing with the 6-digit admin code",
    tags=["devices"],
)
def pair_device(
    body: DevicePairRequest,
    http_request: Request,
    service: DeviceService = Depends(_service),
) -> DevicePairResponse:
    """Create (or re-open) a pending pairing request.

    Returns the canonical minimal body ``{pairing_id, status}`` — never a
    token: the credential is generated by admin approval and handed over
    once by the pairing poll below.

    Rate limited: 5/minute per source IP and 10/minute globally, both in
    process memory (single worker — documented limitation, Phase 16).
    A wrong code is a 401 with a stable error code and is audited by the
    limiter, never by ``audit_logs`` (the code itself is never written).
    """
    ip = _ip(http_request)
    if not pair_limiter_ip.allow(ip or "unknown") or not pair_limiter_global.allow(
        "global"
    ):
        raise PairingRateLimitedError(
            message="Too many pairing attempts; try again in a minute"
        )

    device = service.request_pairing(
        device_id=body.device_id,
        display_name=body.display_name,
        pairing_code=body.pairing_code,
        client_version=body.client_version,
        client_ip=ip,
    )
    return DevicePairResponse(
        pairing_id=device.pairing_id,
        status=device.status,
    )


@router.get(
    POLL_PATH,
    response_model=DevicePairingStatusResponse,
    summary="Poll a pairing request until it is approved",
    tags=["devices"],
)
def poll_pairing(
    pairing_id: uuid.UUID,
    service: DeviceService = Depends(_service),
) -> DevicePairingStatusResponse:
    device, token, token_unavailable = service.poll_pairing(pairing_id)
    return DevicePairingStatusResponse(
        pairing_id=device.pairing_id,
        device_id=device.device_id,
        display_name=device.display_name,
        status=device.status,
        approved_at=device.approved_at,
        rejected_at=device.rejected_at,
        device_token=token,
        token_unavailable=token_unavailable,
        server_id=get_server_id(),
        server_name=settings.STORE_NAME,
        http_port=settings.PORT,
    )


